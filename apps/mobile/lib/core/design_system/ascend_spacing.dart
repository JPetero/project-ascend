/// Project Ascend's spacing scale. Only these values should be used for
/// padding, margins, and gaps so the UI stays visually consistent.
abstract final class AscendSpacing {
  static const double xs = 4;
  static const double sm = 8;
  static const double smMd = 12;
  static const double md = 16;
  static const double mdLg = 20;
  static const double lg = 24;
  static const double xl = 32;
  static const double xxl = 40;
  static const double xxxl = 48;
  static const double huge = 64;
  static const double massive = 96;
}
